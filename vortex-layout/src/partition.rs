/// Positional index for a schema's original or generated field at some level.
/// It's up to the layout/plan to interpret its meaning.
pub type FieldIndex = usize;

pub struct NodeTouches {
    /// Output slots node needs. May include slots that are not present in
    /// input but are generated by the node
    pub slots: Vec<FieldIndex>,
    /// Expression that combines slots in "slots" with optional extra work
    pub replacement: BoundExpression,
}

pub fn replacement_scope(dtypes: &[DType]) -> BoundExpression {
    BoundExpression::new_root(positional_scope(dtypes.to_vec()))
}

/// Read slot "i" of "expr"
pub fn slot_read(expr: &BoundExpression, i: usize) -> BoundExpression {
    get_item(positional_name(i), expr.clone())
}

/// Struct { i: dtype} for i in dtypes
fn positional_scope(dtypes: Vec<DType>) -> DType {
    DType::Struct(
        StructFields::new((0..dtypes.len()).map(positional_name).collect(), dtypes),
        Nullability::NonNullable,
    )
}

pub(crate) fn scope_of(expr: &BoundExpression) -> Option<&DType> {
    if expr.is_root() {
        return Some(expr.dtype());
    }
    expr.children().iter().find_map(scope_of)
}

pub trait PartitionRule: Send + Sync {
    /// None if rule doesn't apply, otherwise list of slots node needs as well
    /// as a combiner expression for these slots
    fn apply(&self, node: &BoundExpression) -> VortexResult<Option<NodeTouches>>;
}

pub struct PartitionRules {
    /// Root expression rule
    pub scope: Box<dyn PartitionRule>,
    /// Non-root expression rules
    pub by_fn: HashMap<Id, Box<dyn PartitionRule>>,
}

impl fmt::Debug for PartitionRules {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("PartitionRules").finish_non_exhaustive()
    }
}

#[derive(Clone, Debug)]
pub struct PartitionSession {
    registry: ArcSwapMap<Id, Arc<PartitionRules>>,
}

impl PartitionSession {
    pub fn register(&self, id: Id, rules: PartitionRules) {
        self.registry.insert(id, Arc::new(rules));
    }

    pub fn rules(&self, id: Id) -> Option<Arc<PartitionRules>> {
        self.registry.get(&id)
    }
}

impl Default for PartitionSession {
    fn default() -> Self {
        let this = Self {
            registry: ArcSwapMap::default(),
        };
        this.register(Pack.id(), struct_partition_rules());
        this.register(RowIdx.id(), row_idx_partition_rules());
        this
    }
}

impl SessionVar for PartitionSession {
    fn as_any(&self) -> &dyn Any {
        self
    }

    fn as_any_mut(&mut self) -> &mut dyn Any {
        self
    }
}

pub enum PartitionedExpression {
    /// If None, expression may go into any partition
    /// If some, expression reference exactly one field from children
    One(Option<FieldIndex>, BoundExpression),
    /// Expression references multiple fields from children
    Many(Partitions),
}

pub struct Partitions {
    /// Expression that combines "partitions"
    pub root: BoundExpression,
    pub partitions: Vec<Partition>,
}

pub struct Partition {
    pub slot: FieldIndex,
    pub expr: BoundExpression,
}

pub fn partition_expression(
    expr: &BoundExpression,
    source: Id,
    session: &VortexSession,
) -> VortexResult<PartitionedExpression> {
    let rules = session
        .get::<PartitionSession>()
        .rules(source)
        .ok_or_else(|| vortex_err!("No partition rules for {source}"))?;
    let mut order = linearize(expr, &rules)?;
    let mut parts = Parts::default();
    let mut results: Vec<Option<Analyzed>> = Vec::with_capacity(order.len());
    for i in 0..order.len() {
        let analyzed = match order[i].touches.take() {
            Some(touches) => replaced(&mut parts, touches)?,
            None => analyze(i, &order, &mut results, &mut parts)?,
        };
        results.push(Some(analyzed));
    }

    let root = match results.pop().flatten().vortex_expect("root not traversed") {
        Analyzed::Bound(slot, expr) => {
            return Ok(PartitionedExpression::One(slot, expr.into_owned()));
        }
        Analyzed::Root(root) => root,
    };

    let mut partitions = Vec::with_capacity(parts.parts.len());
    let mut flattened = HashSet::default();
    for (i, part) in parts.parts.into_iter().enumerate() {
        let mut exprs = part.exprs.into_iter();
        let expr = if exprs.len() == 1 {
            flattened.insert(positional_name(i));
            exprs.next().vortex_expect("a single child")
        } else {
            pack(
                exprs
                    .enumerate()
                    .map(|(sub, expr)| (positional_name(sub), expr)),
                Nullability::NonNullable,
            )
        };
        partitions.push(Partition {
            slot: part.slot,
            expr,
        });
    }

    let dtypes: Vec<DType> = partitions
        .iter()
        .map(|partition| partition.expr.dtype().clone())
        .collect();
    let root = if flattened.is_empty() {
        root
    } else {
        flatten_refs(&root, &flattened)?
    };
    let mut root = root.bind(&positional_scope(dtypes))?;
    if parts.substituted {
        root = root.optimize_recursive()?;
    }
    Ok(PartitionedExpression::Many(Partitions { root, partitions }))
}

struct Entry<'a> {
    node: &'a BoundExpression,
    size: usize,
    touches: Option<NodeTouches>,
}

fn linearize<'a>(
    expr: &'a BoundExpression,
    rules: &PartitionRules,
) -> VortexResult<Vec<Entry<'a>>> {
    let mut order = Vec::new();
    let mut stack = vec![(expr, 0usize, 0usize)];
    while let Some((node, child, mark)) = stack.pop() {
        if child == 0 {
            if let Some(touches) = apply_rule(rules, node)? {
                order.push(Entry {
                    node,
                    size: 1,
                    touches: Some(touches),
                });
                continue;
            }
            vortex_ensure!(!node.is_root());
        }
        if child < node.children().len() {
            stack.push((node, child + 1, mark));
            stack.push((&node.children()[child], 0, order.len()));
        } else {
            order.push(Entry {
                node,
                size: order.len() - mark + 1,
                touches: None,
            });
        }
    }
    Ok(order)
}

enum Analyzed<'a> {
    /// This expression references at most one field from children.
    /// If it's Cow::Borrowed, we keep the original expression
    Bound(Option<FieldIndex>, Cow<'a, BoundExpression>),
    /// This expression reference many fields from children and is replaced
    /// with a new root expression.
    Root(Expression),
}

fn analyze<'a>(
    i: usize,
    order: &[Entry<'a>],
    results: &mut [Option<Analyzed<'a>>],
    parts: &mut Parts,
) -> VortexResult<Analyzed<'a>> {
    let node = order[i].node;
    let scalar_fn = node.as_scalar().vortex_expect("not a scalar function");

    let mut slot = None;
    let mut many = false;
    let mut changed = false;
    let mut children = Vec::with_capacity(node.children().len());
    let mut next = i;
    for _ in 0..node.children().len() {
        let index = next - 1;
        next -= order[index].size;
        let analyzed = results[index].take().vortex_expect("children are analyzed");
        match &analyzed {
            Analyzed::Bound(child_slot, expr) => {
                changed |= matches!(expr, Cow::Owned(_));
                match (slot, *child_slot) {
                    (None, child_slot) => slot = child_slot,
                    (Some(current), Some(child_slot)) if current != child_slot => many = true,
                    _ => {}
                }
            }
            Analyzed::Root(_) => many = true,
        }
        children.push(analyzed);
    }
    children.reverse();

    if many {
        let children = children
            .into_iter()
            .map(|child| match child {
                Analyzed::Bound(None, expr) => to_unbound(&expr, None),
                Analyzed::Bound(Some(slot), expr) => Ok(parts.cut(slot, expr.into_owned())),
                Analyzed::Root(expr) => Ok(expr),
            })
            .collect::<VortexResult<Vec<_>>>()?;
        return Ok(Analyzed::Root(Expression::try_new(
            scalar_fn.clone(),
            children,
        )?));
    }

    if !changed {
        return Ok(Analyzed::Bound(slot, Cow::Borrowed(node)));
    }

    let exprs = children
        .into_iter()
        .map(|child| match child {
            Analyzed::Bound(_, expr) => Ok(expr.into_owned()),
            Analyzed::Root(_) => Err(vortex_err!("multiple slot referencing child")),
        })
        .collect::<VortexResult<Vec<_>>>()?;
    Ok(Analyzed::Bound(
        slot,
        Cow::Owned(BoundExpression::try_new(scalar_fn.clone(), exprs)?),
    ))
}

fn replaced<'a>(parts: &mut Parts, touches: NodeTouches) -> VortexResult<Analyzed<'a>> {
    let NodeTouches { slots, replacement } = touches;
    if slots.len() <= 1 {
        let idx = slots.first().copied();
        let replacement = Cow::Owned(replacement);
        return Ok(Analyzed::Bound(idx, replacement));
    }
    let fields = scope_of(&replacement)
        .and_then(DType::as_struct_fields_opt)
        .ok_or_else(|| vortex_err!("Reading a non-existent field"))?;
    vortex_ensure!(fields.nfields() == slots.len());
    parts.substituted = true;
    let scope = unbound::pack(
        slots
            .into_iter()
            .zip(fields.fields())
            .enumerate()
            .map(|(position, (slot, dtype))| {
                let read = parts.cut(slot, BoundExpression::new_root(dtype));
                (positional_name(position), read)
            }),
        Nullability::NonNullable,
    );
    Ok(Analyzed::Root(to_unbound(&replacement, Some(&scope))?))
}

const NAMES_LEN: usize = 100;
static NAMES: LazyLock<[FieldName; NAMES_LEN]> =
    LazyLock::new(|| std::array::from_fn(|position| FieldName::from(format!("{position}"))));
pub(crate) fn positional_name(position: usize) -> FieldName {
    NAMES
        .get(position)
        .cloned()
        .unwrap_or_else(|| format!("{position}").into())
}

fn apply_rule(rules: &PartitionRules, node: &BoundExpression) -> VortexResult<Option<NodeTouches>> {
    if node.is_root() {
        return rules.scope.apply(node);
    }
    match node.as_scalar().and_then(|fn_| rules.by_fn.get(&fn_.id())) {
        Some(rule) => rule.apply(node),
        None => Ok(None),
    }
}

struct PartBuild {
    slot: FieldIndex,
    positions: HashMap<BoundExpression, usize>,
    exprs: Vec<BoundExpression>,
}

impl PartBuild {
    fn push_dedup(&mut self, expr: BoundExpression) -> usize {
        let exprs = &mut self.exprs;
        *self.positions.entry(expr.clone()).or_insert_with(|| {
            exprs.push(expr);
            exprs.len() - 1
        })
    }
}

#[derive(Default)]
struct Parts {
    index: HashMap<FieldIndex, usize>,
    parts: Vec<PartBuild>,
    substituted: bool,
}

impl Parts {
    fn cut(&mut self, slot: FieldIndex, expr: BoundExpression) -> Expression {
        let part = *self.index.entry(slot).or_insert_with(|| {
            self.parts.push(PartBuild {
                slot,
                positions: HashMap::default(),
                exprs: Vec::new(),
            });
            self.parts.len() - 1
        });
        let sub = self.parts[part].push_dedup(expr);
        unbound::get_item(
            positional_name(sub),
            unbound::get_item(positional_name(part), unbound::root()),
        )
    }
}

fn to_unbound(expr: &BoundExpression, scope: Option<&Expression>) -> VortexResult<Expression> {
    let Some(scalar_fn) = expr.as_scalar() else {
        return scope.cloned().ok_or_else(|| vortex_err!("scope reference"));
    };
    let children = expr
        .children()
        .iter()
        .map(|child| to_unbound(child, scope))
        .collect::<VortexResult<Vec<_>>>()?;
    Expression::try_new(scalar_fn.clone(), children)
}

/// References produced in cut() have two levels. If reference is used only
/// once, we can remove one level of indirection here. $.0.x -> $.x
fn flatten_refs(node: &Expression, flattened: &HashSet<FieldName>) -> VortexResult<Expression> {
    if let Some(name) = node.as_opt::<GetItem>()
        && *name == positional_name(0)
        && let Some(child_name) = node.child(0).as_opt::<GetItem>()
        && node.child(0).child(0).is_root()
        && flattened.contains(child_name)
    {
        return Ok(node.child(0).clone());
    }
    if node.children().is_empty() {
        return Ok(node.clone());
    }
    let children = node
        .children()
        .iter()
        .map(|child| flatten_refs(child, flattened))
        .collect::<VortexResult<Vec<_>>>()?;
    node.clone().with_children(children)
}
