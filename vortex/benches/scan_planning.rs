struct TableFixture {
    file: VortexFile,
    /// Every segment of the file, read once in setup.
    segments: HashMap<SegmentId, BufferHandle>,
}

impl TableFixture {
    fn new(table: Table) -> Self {
        let file = table_file(table);
        let source = file.segment_source();
        let count = file.footer().segment_map().len();
        let segments = (0..count)
            .map(|id| {
                let id = SegmentId::from(u32::try_from(id).unwrap());
                (id, RUNTIME.block_on(source.request(id)).unwrap())
            })
            .collect();
        Self { file, segments }
    }

    /// The file's scan parts, without a cache, as a first scan of a file sees them.
    fn cold(&self) -> ScanFile {
        ScanFile {
            cache: None,
            ..self.file.scan_file()
        }
    }
}

/// What one filtered chunk of a query compiles, captured from a run of the chunk.
struct ChunkStep {
    plan: PlanRef,
    split: Split,
    /// Whether this is a conjunct, whose output becomes a mask.
    conjunct: bool,
}

struct QueryFixture {
    table: Table,
    projection: BoundExpression,
    filter: Option<BoundExpression>,
    scan: PreparedScan,
    /// The pruning plans a prune planner over the file runs, each with the split it compiles
    /// under: the rows the earlier pruning plans kept.
    pruning: Vec<PlanRef>,
    prune_splits: Vec<Split>,
    prune_rows: std::ops::Range<u64>,
    /// The plans the chunk's announcement compiles to list their segments, under the mask the
    /// chunk starts with: every conjunct but the first, whose scan lists its own, and the
    /// projection.
    announce: Vec<PlanRef>,
    chunk_start: Split,
    /// Each conjunct's scan, then the scan of each projection piece.
    steps: Vec<ChunkStep>,
}

struct Fixtures {
    tables: HashMap<Table, TableFixture>,
    queries: HashMap<&'static str, QueryFixture>,
}

static FIXTURES: LazyLock<Fixtures> = LazyLock::new(|| {
    let tables: HashMap<Table, TableFixture> = [Table::Lineitem, Table::Orders]
        .into_iter()
        .map(|table| (table, TableFixture::new(table)))
        .collect();
    let queries = QUERIES
        .iter()
        .map(|query| (query.name, query_fixture(query, &tables[&query.table])))
        .collect();
    Fixtures { tables, queries }
});

fn bound(query: &Query, file: &VortexFile) -> (BoundExpression, Option<BoundExpression>) {
    let projection = pack(
        query.projection.iter().map(|name| (*name, col(name))),
        Nullability::NonNullable,
    )
    .bind(file.dtype())
    .unwrap();
    let filter = (query.filter)().map(|filter| filter.bind(file.dtype()).unwrap());
    (projection, filter)
}

fn builder(
    fixture: &TableFixture,
    projection: &BoundExpression,
    filter: Option<&BoundExpression>,
) -> ScanBuilder {
    ScanBuilder::new(SESSION.clone(), fixture.cold())
        .with_projection(projection.clone())
        .with_some_filter(filter.cloned())
}

/// A scan of `plan` over `split`, as the scan's planners construct one.
fn new_scan(prepared: &PreparedScan, plan: &PlanRef, split: &Split) -> Scan {
    Scan::try_new(SESSION.clone(), plan.clone(), vec![split.clone()])
        .unwrap()
        .with_row_offset(prepared.row_offset())
        .with_value_cache(prepared.value_cache().clone())
}

/// Runs `scan` to completion over in-memory segments.
fn run(mut scan: Scan, segments: &HashMap<SegmentId, BufferHandle>) -> Vec<ArrayRef> {
    let mut out = Vec::new();
    loop {
        match scan.step().unwrap() {
            Turn::Read(read) => scan
                .deliver(read.id, segments[&read.segment_id].clone())
                .unwrap(),
            Turn::Output(_, array) => out.push(array),
            Turn::Waiting => unreachable!("every read is delivered at once"),
            Turn::Done => return out,
        }
    }
}

/// The mask of the rows `pieces` keep, nulls as false, as the planners derive one.
fn pieces_mask(pieces: Vec<ArrayRef>) -> Mask {
    let mut ctx = SESSION.create_execution_ctx();
    let masks = pieces
        .into_iter()
        .map(|piece| {
            piece
                .fill_null(false)
                .unwrap()
                .execute::<Mask>(&mut ctx)
                .unwrap()
        })
        .collect::<Vec<_>>();
    Mask::concat(masks.iter()).unwrap()
}

fn query_fixture(query: &Query, table: &TableFixture) -> QueryFixture {
    let (projection, filter) = bound(query, &table.file);
    let scan = builder(table, &projection, filter.as_ref())
        .prepare()
        .unwrap();
    let row_count = table.file.row_count();

    // A prune planner over the whole file, as an engine with one partition per file runs it.
    let prune_rows = 0..row_count;
    let pruning: Vec<PlanRef> = scan
        .filter()
        .map(|filter| filter.pruning_over(row_count).cloned().collect())
        .unwrap_or_default();
    let mut kept = Mask::new_true(row_count as usize);
    let mut prune_splits = Vec::new();
    for plan in &pruning {
        let split = Split {
            rows: prune_rows.clone(),
            mask: kept.clone(),
        };
        let excluded = pieces_mask(run(new_scan(&scan, plan, &split), &table.segments));
        kept = kept.intersect_by_rank(&!excluded);
        prune_splits.push(split);
    }

    // The first chunk, with its conjuncts in their initial order. Pruning keeps every row of it,
    // so its rows need no trimming to the kept ones.
    let chunk = 0..(scan.chunk_rows() as u64).min(row_count);
    let mut mask = kept.slice(0..chunk.end as usize);
    assert!(
        mask.all_true(),
        "{}: pruning drops rows of the first chunk",
        query.name
    );
    let chunk_start = Split {
        rows: chunk.clone(),
        mask: mask.clone(),
    };
    let predicates = scan
        .filter()
        .map(|filter| filter.predicate_plans().to_vec())
        .unwrap_or_default();
    // The first conjunct's scan lists its own segments; the planner announces the rest by
    // compiling them.
    let mut announce = predicates.iter().skip(1).cloned().collect::<Vec<_>>();
    announce.push(scan.projection_plan().clone());
    let mut steps = Vec::new();
    for plan in &predicates {
        if mask.all_false() {
            break;
        }
        let split = Split {
            rows: chunk.clone(),
            mask: mask.clone(),
        };
        let result = pieces_mask(run(new_scan(&scan, plan, &split), &table.segments));
        mask = mask.intersect_by_rank(&result);
        steps.push(ChunkStep {
            plan: plan.clone(),
            split,
            conjunct: true,
        });
    }
    // The projection runs as one morsel per piece of the selected rows, each through a
    // selection-bound plan of its rows.
    if !mask.all_false() {
        for (rows, mask) in projection_pieces(chunk, mask) {
            let split = Split::all(rows.clone());
            let plan = scan.selected_projection(rows, mask);
            run(new_scan(&scan, &plan, &split), &table.segments);
            steps.push(ChunkStep {
                plan,
                split,
                conjunct: false,
            });
        }
    }
    // Every timed scan compiles without running a pipeline to output.
    for step in &steps {
        let turn = new_scan(&scan, &step.plan, &step.split).step().unwrap();
        assert!(
            matches!(turn, Turn::Read(_)),
            "{}: a chunk scan's first turn is {}",
            query.name,
            turn_kind(&turn)
        );
    }
    QueryFixture {
        table: query.table,
        projection,
        filter,
        scan,
        pruning,
        prune_splits,
        prune_rows,
        announce,
        chunk_start,
        steps,
    }
}

/// Compiles `plan` over `split` and runs the scan to its first turn.
fn compile(prepared: &PreparedScan, plan: &PlanRef, split: &Split) -> Scan {
    let mut scan = new_scan(prepared, plan, split);
    divan::black_box(scan.step().unwrap());
    scan
}

/// The segments each of `plans` reads over `split`, as a planner's announcement collects them.
fn announce(plans: &[PlanRef], split: &Split) -> Vec<SegmentId> {
    let mut segments = Vec::new();
    for plan in plans {
        segments.extend(Scan::segments(&SESSION, plan, split.rows.clone(), &split.mask).unwrap());
    }
    segments.sort_unstable();
    segments.dedup();
    segments
}

