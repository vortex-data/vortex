//! Isolates V2 scan planning, compilation and operator execution over real TPC-H files and the
//! scans real TPC-H queries push into them.
//!
//! Each query is the projection and the filter DataFusion pushes into one table's Vortex scan:
//! the projection packs the columns the plan above the scan reads, and the filter holds the
//! table-local conjuncts after constant folding, literal coercion, IN-list simplification and
//! join-predicate factoring. Dynamic join and TopK filters, which DataFusion adds to probe-side
//! scans at run time, are not modelled. The files are TPC-H tables generated by `tpchgen` and
//! written with the default write strategy.
//!
//! Setup runs every scan of a query's first chunk to completion once, over segments prefetched
//! into memory, to derive the masks a real chunk compiles each step against. That also builds
//! the plan's lazy child slots and fills the scan's dictionary value cache, so the chunk
//! benchmarks see the state of a scan's second and later chunks:
//!
//! - `lower`: lowering a table's layout into its root plan. Child plans are built lazily on
//!   first access, so the rest of the lowering is part of `prepare`.
//! - `prepare`: preparing a scan with a cold scan cache over an opened footer, which lowers the
//!   layout and plans the filter and the projection. This runs once per file per query.
//! - `prune_compile`: what the first [`PrunePlanner`] over a file compiles before reading any
//!   segment: the announced segments of every pruning plan and the scan of each, under the rows
//!   the earlier pruning plans kept. Pruning plans remember the zones they proved, so each
//!   iteration compiles the plans of a freshly prepared scan.
//! - `chunk_compile`: what one filtered chunk compiles before reading any segment, in the order
//!   its planners do: the scan of the first conjunct, which lists its own segments for the
//!   chunk's announcement, the announced segments of the other conjuncts and of the projection,
//!   a scan per later conjunct under the mask the earlier conjuncts left, and the scan of each
//!   projection piece under the final mask.
//! - `chunk_run`: the chunk's scans, compiled outside the timed region, run to completion over
//!   in-memory segments: the operators, the pipeline driver, and the decoding and lazy array
//!   work the operators do.
//! - `chunk_execute`: the chunk planned and run to completion over in-memory segments, for
//!   scale: the compile share of a chunk's scan work is `chunk_compile / chunk_execute`. Arrow
//!   conversion and the engine's work on the batches are not included.
//!
//! A compiled scan is timed until its first [`Turn`]: [`Scan::step`] compiles the whole stage
//! when it activates the split, and then returns as soon as a pipeline asks for a segment.
//! Setup checks that every chunk scan's first turn is a read.
//!
//! Set `VORTEX_BENCH_TPCH_SF` to change the scale factor, 1 by default. Generated files are
//! cached under Cargo's target temporary directory. Set `VORTEX_BENCH_DESCRIBE` to print what
//! every fixture compiles before benchmarking.
//!
//! [`PrunePlanner`]: vortex_layout::scan::v2::PrunePlanner

