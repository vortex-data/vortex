/// Prints what every fixture compiles, to check the benchmarks against the real scans.
fn describe() {
    for (table, fixture) in &FIXTURES.tables {
        println!(
            "{}: {} rows, {} segments, dtype {}",
            table.name(),
            fixture.file.row_count(),
            fixture.segments.len(),
            fixture.file.dtype()
        );
    }
    for name in QUERY_NAMES {
        let query = &FIXTURES.queries[name];
        println!("{name}:");
        println!("  projection: {}", query.projection);
        if let Some(filter) = &query.filter {
            println!("  filter: {filter}");
        }
        println!("  chunk rows: {}", query.scan.chunk_rows());
        let split = Split::all(query.prune_rows.clone());
        println!(
            "  pruning plans: {}, warm announcing {} segments",
            query.pruning.len(),
            announce(&query.pruning, &split).len()
        );
        let fresh = builder(
            &FIXTURES.tables[&query.table],
            &query.projection,
            query.filter.as_ref(),
        )
        .prepare()
        .unwrap();
        let fresh_pruning: Vec<PlanRef> = fresh
            .filter()
            .map(|filter| {
                filter
                    .pruning_over(split.rows.end - split.rows.start)
                    .cloned()
                    .collect()
            })
            .unwrap_or_default();
        println!(
            "  cold pruning announces {} segments",
            announce(&fresh_pruning, &split).len()
        );
        for (plan, split) in fresh_pruning.iter().zip(&query.prune_splits) {
            let turn = new_scan(&fresh, plan, split).step().unwrap();
            println!(
                "    cold first turn: {} over {} rows",
                turn_kind(&turn),
                split.mask.true_count()
            );
        }
        if query.scan.filter().is_some() {
            println!(
                "  chunk {}..{}: {} rows kept by pruning, announcing {} segments",
                query.chunk_start.rows.start,
                query.chunk_start.rows.end,
                query.chunk_start.mask.true_count(),
                announce(&query.announce, &query.chunk_start).len()
            );
        }
        for step in &query.steps {
            let turn = new_scan(&query.scan, &step.plan, &step.split)
                .step()
                .unwrap();
            println!(
                "    {} over {} of {} rows, first turn: {}",
                if step.conjunct {
                    "conjunct"
                } else {
                    "projection"
                },
                step.split.mask.true_count(),
                step.split.mask.len(),
                turn_kind(&turn)
            );
        }
    }
}

fn turn_kind(turn: &Turn) -> &'static str {
    match turn {
        Turn::Read(_) => "read",
        Turn::Output(..) => "output",
        Turn::Waiting => "waiting",
        Turn::Done => "done",
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
enum Table {
    Lineitem,
    Orders,
}

impl Table {
    fn name(self) -> &'static str {
        match self {
            Table::Lineitem => "lineitem",
            Table::Orders => "orders",
        }
    }
}

fn scale_factor() -> f64 {
    std::env::var("VORTEX_BENCH_TPCH_SF")
        .ok()
        .map(|sf| sf.parse().unwrap())
        .unwrap_or(1.0)
}

/// Generates `table` at the configured scale factor, writes it with the default write strategy,
/// and caches the file across runs.
fn table_file(table: Table) -> VortexFile {
    let sf = scale_factor();
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(format!("tpch-sf{sf}"));
    let path = dir.join(format!("{}.vortex", table.name()));
    if !path.exists() {
        std::fs::create_dir_all(&dir).unwrap();
        let batches: Vec<RecordBatch> = match table {
            Table::Lineitem => tpchgen_arrow::LineItemArrow::new(LineItemGenerator::new(sf, 1, 1))
                .with_batch_size(65_536)
                .collect::<Result<_, _>>()
                .unwrap(),
            Table::Orders => tpchgen_arrow::OrderArrow::new(OrderGenerator::new(sf, 1, 1))
                .with_batch_size(65_536)
                .collect::<Result<_, _>>()
                .unwrap(),
        };
        let chunks = batches
            .into_iter()
            .map(|batch| {
                let schema = batch.schema();
                SESSION
                    .arrow()
                    .from_arrow_record_batch(batch, &schema)
                    .unwrap()
            })
            .collect::<Vec<_>>();
        let array = ChunkedArray::from_iter(chunks).into_array();
        let mut buf = ByteBufferMut::empty();
        RUNTIME
            .block_on(
                SESSION
                    .write_options()
                    .write(&mut buf, array.to_array_stream()),
            )
            .unwrap();
        let tmp = path.with_extension("tmp");
        std::fs::write(&tmp, buf.as_ref()).unwrap();
        std::fs::rename(&tmp, &path).unwrap();
    }
    SESSION
        .open_options()
        .open_buffer(std::fs::read(&path).unwrap())
        .unwrap()
}

/// A scan a TPC-H query pushes into one table.
struct Query {
    name: &'static str,
    table: Table,
    /// The columns the plan above the scan reads, in schema order.
    projection: &'static [&'static str],
    filter: fn() -> Option<Expression>,
}

fn col(name: &str) -> Expression {
    get_item(name, root())
}

/// Imports one Arrow value as DataFusion imports a literal coerced to its column's type.
fn import(array: ArrowArrayRef) -> Expression {
    let field = ArrowField::new("", array.data_type().clone(), false);
    let mut ctx = SESSION.create_execution_ctx();
    let scalar: Scalar = SESSION
        .arrow()
        .from_arrow_array(array, &field)
        .unwrap()
        .execute_scalar(0, &mut ctx)
        .unwrap();
    lit(scalar)
}

/// Days since the Unix epoch of a proleptic Gregorian date.
fn days(year: i32, month: u32, day: u32) -> i32 {
    let year = if month <= 2 { year - 1 } else { year };
    let era = year.div_euclid(400);
    let year_of_era = year - era * 400;
    let month = month as i32;
    let day_of_year =
        (153 * (if month > 2 { month - 3 } else { month + 9 }) + 2) / 5 + day as i32 - 1;
    let day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    era * 146_097 + day_of_era - 719_468
}

fn date(year: i32, month: u32, day: u32) -> Expression {
    import(Arc::new(Date32Array::from(vec![days(year, month, day)])))
}

/// A `DECIMAL(15, 2)` literal of `cents` hundredths.
fn decimal(cents: i128) -> Expression {
    import(Arc::new(
        Decimal128Array::from(vec![cents])
            .with_precision_and_scale(15, 2)
            .unwrap(),
    ))
}

fn string(value: &str) -> Expression {
    import(Arc::new(StringViewArray::from(vec![value])))
}

fn conjunction(conjuncts: Vec<Expression>) -> Option<Expression> {
    and_collect(conjuncts)
}

