/// Pruning plans remember the zones they proved, so each iteration compiles the pruning plans of
/// a freshly prepared scan, as the first prune planner over a file does.
#[divan::bench(args = QUERY_NAMES)]
fn prune_compile(bencher: Bencher, query: &str) {
    let query = &FIXTURES.queries[query];
    let table = &FIXTURES.tables[&query.table];
    let first = Split::all(query.prune_rows.clone());
    bencher
        .with_inputs(|| {
            let scan = builder(table, &query.projection, query.filter.as_ref())
                .prepare()
                .unwrap();
            let pruning: Vec<PlanRef> = scan
                .filter()
                .map(|filter| {
                    filter
                        .pruning_over(query.prune_rows.end - query.prune_rows.start)
                        .cloned()
                        .collect()
                })
                .unwrap_or_default();
            (scan, pruning)
        })
        .bench_local_refs(|(scan, pruning)| {
            let segments = announce(pruning, &first);
            let scans = pruning
                .iter()
                .zip(&query.prune_splits)
                .map(|(plan, split)| compile(scan, plan, split))
                .collect::<Vec<_>>();
            (segments, scans)
        });
}

/// The segments a filter planner announces for its chunk: those the first conjunct's scan
/// compiled, and those the other plans compile to.
fn announce_chunk(query: &QueryFixture, first: &mut Scan) -> Vec<SegmentId> {
    let mut segments = first.compiled_segments().unwrap().to_vec();
    segments.extend(announce(&query.announce, &query.chunk_start));
    segments.sort_unstable();
    segments.dedup();
    segments
}

#[divan::bench(args = QUERY_NAMES)]
fn chunk_compile(bencher: Bencher, query: &str) {
    let query = &FIXTURES.queries[query];
    bencher.bench(|| {
        let mut steps = query.steps.iter();
        let mut scans = Vec::with_capacity(query.steps.len());
        let mut segments = None;
        if query.scan.filter().is_some() {
            let step = steps.next().unwrap();
            let mut first = new_scan(&query.scan, &step.plan, &step.split);
            segments = Some(announce_chunk(query, &mut first));
            divan::black_box(first.step().unwrap());
            scans.push(first);
        }
        scans.extend(steps.map(|step| compile(&query.scan, &step.plan, &step.split)));
        (segments, scans)
    });
}

#[divan::bench(args = QUERY_NAMES, sample_count = 20)]
fn chunk_execute(bencher: Bencher, query: &str) {
    let query = &FIXTURES.queries[query];
    let segments = &FIXTURES.tables[&query.table].segments;
    bencher.bench(|| {
        let mut steps = query.steps.iter().peekable();
        let mut announced = None;
        let mut first = None;
        if query.scan.filter().is_some() {
            let step = steps.peek().unwrap();
            let mut scan = new_scan(&query.scan, &step.plan, &step.split);
            announced = Some(announce_chunk(query, &mut scan));
            first = Some(scan);
        }
        let mut masks = Vec::new();
        let mut outputs = Vec::new();
        for step in steps {
            let scan = first
                .take()
                .unwrap_or_else(|| new_scan(&query.scan, &step.plan, &step.split));
            let pieces = run(scan, segments);
            if step.conjunct {
                masks.push(pieces_mask(pieces));
            } else {
                outputs.push(pieces);
            }
        }
        (announced, masks, outputs)
    });
}

/// Runs every scan of the chunk, compiled outside the timed region up to its first turn, to
/// completion over in-memory segments: the operators, the pipeline driver, and the decoding and
/// array work the operators do.
#[divan::bench(args = QUERY_NAMES, sample_count = 20)]
fn chunk_run(bencher: Bencher, query: &str) {
    let query = &FIXTURES.queries[query];
    let segments = &FIXTURES.tables[&query.table].segments;
    bencher
        .with_inputs(|| {
            query
                .steps
                .iter()
                .map(|step| {
                    let mut scan = new_scan(&query.scan, &step.plan, &step.split);
                    let turn = scan.step().unwrap();
                    (scan, turn)
                })
                .collect::<Vec<_>>()
        })
        .bench_local_values(|scans| {
            scans
                .into_iter()
                .map(|(mut scan, mut turn)| {
                    let mut out = Vec::new();
                    loop {
                        match turn {
                            Turn::Read(read) => scan
                                .deliver(read.id, segments[&read.segment_id].clone())
                                .unwrap(),
                            Turn::Output(_, array) => out.push(array),
                            Turn::Waiting => unreachable!("every read is delivered at once"),
                            Turn::Done => return out,
                        }
                        turn = scan.step().unwrap();
                    }
                })
                .collect::<Vec<_>>()
        });
}
