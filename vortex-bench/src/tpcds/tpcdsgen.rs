const BATCH_SIZE: usize = 8192 * 16;

/// Matches the row group size of DuckDB's Parquet writer, which previously generated this data.
const ROW_GROUP_SIZE: usize = 122_880;

/// Source rows generated by one task. The sales tables emit one row per line item, about a dozen
/// per source row, so a chunk holds up to roughly one row group.
const SOURCE_ROWS_PER_CHUNK: u64 = 8 * 1024;

/// Generate every TPC-DS table as Parquet under `base_dir/parquet`.
///
/// Large tables are split into files of about [`split::TARGET_FILE_COMPRESSED_BYTES`], named by
/// [`split::part_file_name`]; every other table is a single `{table}_0001.parquet`. The files hold
/// the same data and schema as `tpcgen-cli tpcds parquet` of the same `tpcdsgen` version, which
/// generates the SQL logic test data. Tables are written one at a time, each split into chunks of
/// source rows that are generated and encoded in parallel. Already generated tables are skipped.
pub async fn generate_tpcds(base_dir: PathBuf, scale_factor: String) -> Result<PathBuf> {
    let output_dir = base_dir.join(Format::Parquet.name());
    fs::create_dir_all(&output_dir)?;

    let scale_factor: f64 = scale_factor.parse()?;
    // Follow the C `dsdgen` reference rather than the Trino Java port, like `tpcgen-cli` does.
    let session = SessionBuilder::new()
        .with_scale_factor(scale_factor)
        .with_compat_mode(CompatMode::C)
        .build()?;

    let parallelism = get_available_parallelism().unwrap_or(1);
    for table in TABLES {
        let first_file = output_dir.join(split::part_file_name(
            table.get_name(),
            1,
            Format::Parquet.ext(),
        ));
        if first_file.exists() {
            continue;
        }

        let layout = FileLayout::new(table, &session);
        info!(
            table = table.get_name(),
            scale_factor,
            files = layout.num_files,
            "Generating TPC-DS table"
        );
        write_table(
            &output_dir,
            table,
            session.clone(),
            layout,
            SOURCE_ROWS_PER_CHUNK,
            ROW_GROUP_SIZE,
            parallelism,
        )
        .await?;
    }

    Ok(output_dir)
}

