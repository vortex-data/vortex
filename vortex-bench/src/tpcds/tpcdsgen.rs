/// How a TPC-DS table's size scales, used to split it into files.
struct TableSize {
    /// The table whose `tpcdsgen` row count drives generation. Returns tables are generated
    /// from their sales tickets.
    source: Table,
    /// Generated rows per source row, such as line items per ticket.
    rows_per_source_row: f64,
    /// Compressed bytes per row: the mean of the Parquet and default Vortex sizes.
    compressed_bytes_per_row: f64,
}

/// Sizes of the tables that can outgrow one file, measured at scale factor 10. The other tables
/// stay well below [`split::TARGET_FILE_COMPRESSED_BYTES`] even at scale factor 1000.
fn table_size(table: Table) -> Option<TableSize> {
    let (source, rows_per_source_row, compressed_bytes_per_row) = match table {
        Table::StoreSales => (Table::StoreSales, 12.0004, 37.283),
        Table::StoreReturns => (Table::StoreSales, 1.1981, 43.643),
        Table::CatalogSales => (Table::CatalogSales, 9.0008, 54.241),
        Table::CatalogReturns => (Table::CatalogSales, 0.8998, 56.303),
        Table::WebSales => (Table::WebSales, 11.9959, 52.890),
        Table::WebReturns => (Table::WebSales, 1.1987, 55.432),
        Table::Inventory => (Table::Inventory, 1.0, 2.762),
        Table::Customer => (Table::Customer, 1.0, 41.164),
        Table::CustomerAddress => (Table::CustomerAddress, 1.0, 15.311),
        Table::Item => (Table::Item, 1.0, 74.525),
        _ => return None,
    };
    Some(TableSize {
        source,
        rows_per_source_row,
        compressed_bytes_per_row,
    })
}

/// How the rows of one table are spread over its files.
#[derive(Clone, Copy)]
struct FileLayout {
    num_files: usize,
    /// Rows in every file but the last, which also takes any rows beyond the estimate.
    rows_per_file: usize,
}

impl FileLayout {
    #[expect(
        clippy::cast_possible_truncation,
        clippy::cast_precision_loss,
        clippy::cast_sign_loss,
        reason = "row counts are far below the f64 and usize limits"
    )]
    fn new(table: Table, session: &Session) -> Self {
        let Some(size) = table_size(table) else {
            return Self {
                num_files: 1,
                rows_per_file: usize::MAX,
            };
        };
        let rows =
            session.get_scaling().get_row_count(size.source) as f64 * size.rows_per_source_row;
        let num_files = split::num_files(rows * size.compressed_bytes_per_row);
        Self {
            num_files,
            rows_per_file: (rows / num_files as f64).ceil().max(1.0) as usize,
        }
    }
}

/// Batches of `table` for its 1-based, inclusive `source_rows`.
///
/// Source rows are not output rows for every table: the sales tables emit several rows per source
/// row, and the returns tables are generated from their paired sales generator.
fn table_batches(
    table: Table,
    session: Session,
    source_rows: RangeInclusive<u64>,
) -> Box<dyn RecordBatchReader + Send> {
    let (start, end) = source_rows.into_inner();
    macro_rules! batches {
        ($arrow:ident) => {
            Box::new(
                $arrow::new(session)
                    .with_source_row_range(start, end)
                    .with_batch_size(BATCH_SIZE),
            )
        };
    }
    match table {
        Table::CallCenter => batches!(CallCenterArrow),
        Table::CatalogPage => batches!(CatalogPageArrow),
        Table::CatalogReturns => batches!(CatalogReturnsArrow),
        Table::CatalogSales => batches!(CatalogSalesArrow),
        Table::Customer => batches!(CustomerArrow),
        Table::CustomerAddress => batches!(CustomerAddressArrow),
        Table::CustomerDemographics => batches!(CustomerDemographicsArrow),
        Table::DateDim => batches!(DateDimArrow),
        Table::HouseholdDemographics => batches!(HouseholdDemographicsArrow),
        Table::IncomeBand => batches!(IncomeBandArrow),
        Table::Inventory => batches!(InventoryArrow),
        Table::Item => batches!(ItemArrow),
        Table::Promotion => batches!(PromotionArrow),
        Table::Reason => batches!(ReasonArrow),
        Table::ShipMode => batches!(ShipModeArrow),
        Table::Store => batches!(StoreArrow),
        Table::StoreReturns => batches!(StoreReturnsArrow),
        Table::StoreSales => batches!(StoreSalesArrow),
        Table::TimeDim => batches!(TimeDimArrow),
        Table::Warehouse => batches!(WarehouseArrow),
        Table::WebPage => batches!(WebPageArrow),
        Table::WebReturns => batches!(WebReturnsArrow),
        Table::WebSales => batches!(WebSalesArrow),
        Table::WebSite => batches!(WebSiteArrow),
        Table::DbgenVersion => unreachable!("dbgen_version is not generated"),
    }
}

/// Split source rows `1..=source_rows` into ranges of at most `rows_per_chunk` rows.
fn source_row_chunks(
    source_rows: u64,
    rows_per_chunk: u64,
) -> impl Iterator<Item = RangeInclusive<u64>> {
    let rows_per_chunk = rows_per_chunk.max(1);
    (0..source_rows.div_ceil(rows_per_chunk)).map(move |chunk| {
        let start = chunk * rows_per_chunk + 1;
        start..=(start + rows_per_chunk - 1).min(source_rows)
    })
}

/// Write `table` as its Parquet files in `output_dir`, split by `layout`.
///
/// The table is generated as chunks of `source_rows_per_chunk` source rows, which `tpcdsgen` can
/// start at any row, so the output matches generating the table in one pass. Chunks are generated
/// and row groups encoded on up to `parallelism` blocking threads each. Every row group but the
/// last of each file holds exactly `row_group_size` rows, as with one [`ArrowWriter`] per file.
///
/// Files are written to temporary paths and renamed into place last part first, so the first
/// part only exists once the whole table does.
async fn write_table(
    output_dir: &Path,
    table: Table,
    session: Session,
    layout: FileLayout,
    source_rows_per_chunk: u64,
    row_group_size: usize,
    parallelism: usize,
) -> Result<()> {
    // An empty range of source rows, to get the schema.
    let schema = table_batches(table, session.clone(), RangeInclusive::new(1, 0)).schema();
    let props = parquet_writer_properties()
        .set_max_row_group_row_count(Some(row_group_size))
        .build();

    // The factory depends only on the schema and the writer properties, which every file of the
    // table shares, so row groups can be encoded before their file exists.
    let (_, row_group_factory) =
        ArrowWriter::try_new(io::sink(), Arc::clone(&schema), Some(props.clone()))?
            .into_serialized_writer()?;
    let row_group_factory = Arc::new(row_group_factory);

    let (tx, mut rx) = mpsc::channel::<(usize, Vec<ArrowColumnChunk>)>(parallelism);
    let writer = tokio::task::spawn_blocking(move || -> Result<Vec<PathBuf>> {
        let create_file = |path: &Path| -> Result<SerializedFileWriter<File>> {
            let writer = ArrowWriter::try_new(
                File::create(path)?,
                Arc::clone(&schema),
                Some(props.clone()),
            )?;
            Ok(writer.into_serialized_writer()?.0)
        };

        let mut files = Vec::with_capacity(layout.num_files);
        let mut file_writer: Option<SerializedFileWriter<File>> = None;
        while let Some((file, column_chunks)) = rx.blocking_recv() {
            let current = match file_writer.as_mut() {
                Some(current) if file < files.len() => current,
                _ => {
                    if let Some(full) = file_writer.take() {
                        full.close()?;
                    }
                    let path = temp_download_filepath();
                    let next = create_file(&path)?;
                    files.push(path);
                    file_writer.insert(next)
                }
            };

            let mut row_group_writer = current.next_row_group()?;
            for column_chunk in column_chunks {
                column_chunk.append_to_row_group(&mut row_group_writer)?;
            }
            row_group_writer.close()?;
        }

        match file_writer {
            Some(writer) => {
                writer.close()?;
            }
            // An empty table still gets one file carrying its schema.
            None => {
                let path = temp_download_filepath();
                create_file(&path)?.close()?;
                files.push(path);
            }
        }
        Ok(files)
    });

    let source_rows = session.get_scaling().get_row_count(table);
    let produced = async move {
        let mut chunks = stream::iter(source_row_chunks(source_rows, source_rows_per_chunk))
            .map(|rows| {
                let session = session.clone();
                tokio::task::spawn_blocking(move || {
                    table_batches(table, session, rows).collect::<Result<Vec<_>, ArrowError>>()
                })
            })
            .buffered(parallelism);

        let mut row_groups = RowGroups::new(row_group_size, layout);
        let mut encoding = FuturesOrdered::new();
        let mut done = false;
        while !done {
            let mut ready = Vec::new();
            match chunks.try_next().await? {
                Some(batches) => {
                    for batch in batches? {
                        row_groups.push(batch, &mut ready);
                    }
                }
                None => {
                    ready.extend(row_groups.finish());
                    done = true;
                }
            }

            for row_group in ready {
                let row_group_factory = Arc::clone(&row_group_factory);
                encoding.push_back(tokio::task::spawn_blocking(move || {
                    let column_chunks =
                        encode_row_group(&row_group_factory, row_group.index, row_group.batches)?;
                    anyhow::Ok((row_group.file, column_chunks))
                }));
                if encoding.len() >= parallelism
                    && let Some(encoded) = encoding.try_next().await?
                    && tx.send(encoded?).await.is_err()
                {
                    // The writer failed, and returns the error.
                    return Ok(());
                }
            }
        }

        while let Some(encoded) = encoding.try_next().await? {
            if tx.send(encoded?).await.is_err() {
                return Ok(());
            }
        }
        anyhow::Ok(())
    }
    .await;

    let files = writer.await??;
    produced?;

    for (idx, path) in files.iter().enumerate().rev() {
        let name = split::part_file_name(table.get_name(), idx + 1, Format::Parquet.ext());
        fs::rename(path, output_dir.join(name))?;
    }
    Ok(())
}

/// Encode `batches` as row group `index` of a file that `row_group_factory` writes.
fn encode_row_group(
    row_group_factory: &ArrowRowGroupWriterFactory,
    index: usize,
    batches: Vec<RecordBatch>,
) -> Result<Vec<ArrowColumnChunk>> {
    let mut column_writers = row_group_factory.create_column_writers(index)?;
    for batch in batches {
        let schema = batch.schema();
        for ((column_writer, field), column) in column_writers
            .iter_mut()
            .zip(schema.fields())
            .zip(batch.columns())
        {
            for leaf in compute_leaves(field, column)? {
                column_writer.write(&leaf)?;
            }
        }
    }
    Ok(column_writers
        .into_iter()
        .map(|column_writer| column_writer.close())
        .collect::<Result<_, _>>()?)
}

/// The batches of row group `index` in file `file`.
struct RowGroup {
    file: usize,
    index: usize,
    batches: Vec<RecordBatch>,
}

/// Regroups a stream of batches into the files of a [`FileLayout`], each holding row groups of
/// exactly `row_group_size` rows but the last.
struct RowGroups {
    row_group_size: usize,
    layout: FileLayout,
    file: usize,
    rows_in_file: usize,
    row_groups_in_file: usize,
    pending: Vec<RecordBatch>,
    pending_rows: usize,
}

impl RowGroups {
    fn new(row_group_size: usize, layout: FileLayout) -> Self {
        Self {
            row_group_size,
            layout,
            file: 0,
            rows_in_file: 0,
            row_groups_in_file: 0,
            pending: Vec::new(),
            pending_rows: 0,
        }
    }

    /// Add `batch`, pushing every row group it completes to `ready`.
    fn push(&mut self, mut batch: RecordBatch, ready: &mut Vec<RowGroup>) {
        while batch.num_rows() > 0 {
            let len = batch
                .num_rows()
                .min(self.row_group_size - self.pending_rows)
                .min(self.file_rows_left());
            self.pending.push(batch.slice(0, len));
            self.pending_rows += len;
            self.rows_in_file += len;
            batch = batch.slice(len, batch.num_rows() - len);

            if self.pending_rows == self.row_group_size {
                ready.push(self.take_row_group());
            }

            if self.file_rows_left() == 0 {
                ready.extend(self.finish());
                self.file += 1;
                self.rows_in_file = 0;
                self.row_groups_in_file = 0;
            }
        }
    }

    /// The final, partial row group of the current file, if any rows remain.
    fn finish(&mut self) -> Option<RowGroup> {
        (!self.pending.is_empty()).then(|| self.take_row_group())
    }

    /// Rows the current file still takes. The last file takes all remaining rows.
    fn file_rows_left(&self) -> usize {
        if self.file + 1 >= self.layout.num_files {
            usize::MAX
        } else {
            self.layout.rows_per_file - self.rows_in_file
        }
    }

    fn take_row_group(&mut self) -> RowGroup {
        let row_group = RowGroup {
            file: self.file,
            index: self.row_groups_in_file,
            batches: mem::take(&mut self.pending),
        };
        self.pending_rows = 0;
        self.row_groups_in_file += 1;
        row_group
    }
}

#[cfg(test)]
mod tests {
    use arrow_select::concat::concat_batches;
    use parquet::arrow::arrow_reader::ParquetRecordBatchReaderBuilder;
    use rstest::rstest;

    use super::*;

    /// Chunked, parallel generation writes the same rows as one pass over the table, split into
    /// files by the layout, with row groups of exactly `row_group_size` rows but the last of each
    /// file.
    #[rstest]
    #[tokio::test]
    async fn chunked_matches_single_pass(
        #[values(
            Table::StoreSales,
            Table::StoreReturns,
            Table::CatalogReturns,
            Table::WebSales,
            Table::Customer,
            Table::Item
        )]
        table: Table,
        #[values(1, 3)] num_files: usize,
    ) -> Result<()> {
        let session = SessionBuilder::new()
            .with_scale_factor(0.01)
            .with_compat_mode(CompatMode::C)
            .build()?;
        let row_group_size = 300;
        let layout = FileLayout {
            num_files,
            rows_per_file: if num_files == 1 { usize::MAX } else { 400 },
        };
        let dir = tempfile::tempdir()?;
        write_table(
            dir.path(),
            table,
            session.clone(),
            layout,
            97,
            row_group_size,
            4,
        )
        .await?;

        let source_rows = session.get_scaling().get_row_count(table);
        let expected = table_batches(table, session, 1..=source_rows);
        let schema = expected.schema();
        let expected = concat_batches(&schema, &expected.collect::<Result<Vec<_>, _>>()?)?;

        let mut actual = Vec::new();
        let mut file_rows = Vec::new();
        for part in 1..=num_files {
            let path = dir.path().join(split::part_file_name(
                table.get_name(),
                part,
                Format::Parquet.ext(),
            ));
            let reader = ParquetRecordBatchReaderBuilder::try_new(File::open(&path)?)?;
            let row_group_rows: Vec<usize> = reader
                .metadata()
                .row_groups()
                .iter()
                .map(|row_group| usize::try_from(row_group.num_rows()))
                .collect::<Result<_, _>>()?;
            file_rows.push(row_group_rows);
            actual.extend(reader.build()?.collect::<Result<Vec<_>, _>>()?);
        }
        let actual = concat_batches(&schema, &actual)?;
        assert_eq!(actual.columns(), expected.columns());

        let mut rows_left = expected.num_rows();
        let expected_file_rows: Vec<Vec<usize>> = (0..num_files)
            .map(|file| {
                let rows = if file + 1 == num_files {
                    rows_left
                } else {
                    rows_left.min(layout.rows_per_file)
                };
                rows_left -= rows;
                (0..rows)
                    .step_by(row_group_size)
                    .map(|start| row_group_size.min(rows - start))
                    .collect()
            })
            .collect();
        assert!(
            expected_file_rows
                .iter()
                .all(|row_groups| !row_groups.is_empty())
        );
        assert!(expected_file_rows[0].len() > 1);
        assert_eq!(file_rows, expected_file_rows);
        Ok(())
    }
}
