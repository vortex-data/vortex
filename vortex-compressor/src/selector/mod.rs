//! A learned scheme selector: a small decision tree, trained offline on measured candidates,
//! that picks the scheme at each integer compression site without estimating.
//!
//! The tree reads only features that the compressor computes anyway (see [`int_features`]), so
//! selecting costs a few comparisons. When the tree is unsure, or a feature lies outside the
//! range it was trained on, the compressor estimates over the tree's top few schemes instead of
//! all of them.
//!
//! Models are generated by the compressor lab's `train_selector.py` into `generated/`, with the
//! scheme set they were trained on. They are data, not code: nothing is loaded at run time.

